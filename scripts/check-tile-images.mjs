// Reports which tile images referenced by lib/calculator-options.ts are not
// present in public/. Runs automatically before every build.
//
// This is a WARNING, never a failure. Tile artwork is delivered separately from
// the code, and the UI falls back to a labelled placeholder for anything
// missing, so an incomplete set is a valid state to ship. The point is to keep
// a running checklist and to catch typos: garden-party.jpg vs garden_party.jpg
// should surface here, not in front of a bride.
//
//   node scripts/check-tile-images.mjs

import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const source = join(root, "lib", "calculator-options.ts");

let contents;
try {
  contents = readFileSync(source, "utf8");
} catch {
  console.warn(`[tile-images] Could not read ${source}. Skipping check.`);
  process.exit(0);
}

// Pull every `image: "/images/..."` value, keeping the order they appear in so
// the report groups naturally by option list.
const paths = [...contents.matchAll(/image:\s*"([^"]+)"/g)].map((m) => m[1]);

if (!paths.length) {
  console.warn("[tile-images] No image paths found. Did the file format change?");
  process.exit(0);
}

const unique = [...new Set(paths)];
const missing = unique.filter((p) => !existsSync(join(root, "public", p)));
const present = unique.length - missing.length;

// Emit the set of tiles that actually exist. TileGrid consults this so a
// missing image renders as a placeholder on the very first paint. Detecting
// it at runtime via onError is unreliable: a 404 usually resolves before
// React hydrates and attaches the handler, leaving an empty box forever.
const available = unique.filter((p) => !missing.includes(p));
writeFileSync(
  join(root, "lib", "tile-manifest.generated.ts"),
  `// GENERATED by scripts/check-tile-images.mjs on each build. Do not edit.\n` +
    `// Tile images present in public/ at build time.\n` +
    `export const AVAILABLE_TILES: ReadonlySet<string> = new Set(${JSON.stringify(available, null, 2)});\n`
);

if (!missing.length) {
  console.log(`[tile-images] All ${unique.length} tile images present.`);
  process.exit(0);
}

// Group by folder so the output reads as a per-batch checklist.
const byFolder = new Map();
for (const p of missing) {
  const folder = p.split("/").slice(0, -1).join("/");
  if (!byFolder.has(folder)) byFolder.set(folder, []);
  byFolder.get(folder).push(p.split("/").pop());
}

console.warn(`\n[tile-images] ${present} of ${unique.length} present, ${missing.length} still missing:`);
for (const [folder, files] of [...byFolder].sort()) {
  console.warn(`  ${folder}/`);
  for (const f of files.sort()) console.warn(`    - ${f}`);
}
console.warn(
  `[tile-images] Missing tiles render as labelled placeholders, so this does not block the build.\n`
);

// Always succeed. A missing image is an expected interim state.
process.exit(0);
